"""Плагин Adalight: «Компенсация цвета стены».

Лента светит не в глаз, а в стену — видно именно отражение. Белая стена
возвращает все каналы одинаково, цветная — нет: красные обои отдают красный
почти целиком, а зелёный и синий съедают. Поэтому на них красные сцены кажутся
ярче задуманного, а остальные цвета уползают в сторону обоев.

Мод правит кадр перед самой отправкой: приглушает каналы, которые стена и так
отражает хорошо, — тогда отражённый свет ближе к тому цвету, который считало
ядро.

Что здесь физически возможно, а что нет
---------------------------------------
Отражение — умножение по каналам: ``в_глаз = свет_ленты * альбедо_стены``.
Обратная задача решается делением, но делить можно только вниз: поднять канал,
который стена не отражает, нечем — 255 уже максимум. Значит компенсация всегда
идёт за счёт приглушения сильного канала, то есть общей яркости. На насыщенных
обоях «честная» коррекция ослабляет доминирующий канал в десятки раз и
превращает подсветку в тусклую монохромную — поэтому есть «сила компенсации»
и «предел приглушения», а полная коррекция нужна редко.

Совсем недостижимы цвета, которых в отражении стены нет: насыщенно-зелёного на
кроваво-красной стене не даст никакая обработка. Мод не творит чудеса, он
убирает перекос.

Ещё одна честная оговорка: поканальная модель описывает только отражение.
Восприятие сложнее — глаз адаптируется к цвету комнаты, и рядом с красной
стеной фиолетовый кажется синее, чем есть на самом деле. Такие вещи моделью не
берутся, для них в дополнительных настройках есть подстройка каналов на глаз.

Почему считаем прямо в байтах
-----------------------------
В фильтр кадра приходят байты, уже прошедшие гамма-LUT ядра, а ШИМ WS2812B
линеен по значению байта — то есть байт пропорционален излучаемому свету.
Умножение на альбедо происходит именно в линейном свете, так что коррекция —
это простой множитель на байт, без обратной гаммы. Цвет стены, наоборот,
задаётся как sRGB (его берут с фото), поэтому перед делением он линеаризуется.

Как установить
--------------
1. Скопируйте файл в папку плагинов:
   Windows: %APPDATA%\\adalight\\plugins\\
   Linux:   ~/.config/adalight/plugins/
   (кнопка «Открыть папку плагинов» на вкладке «Плагины» откроет её)
2. Перезапустите Adalight и включите мод галочкой.
3. Включите «Калибровку», сфотографируйте стену в темноте, возьмите цвет
   пипеткой с фото и вставьте его в «Цвет стены». Калибровку выключите.

Мод работает во всех режимах (подсветка, лампа, цветомузыка и тесты ленты) —
фильтр кадра стоит последним в тракте, перед отправкой.
"""

from __future__ import annotations

import numpy as np

# Rec. 709 — вклад каналов в воспринимаемую яркость (режим «Яркость»).
LUMA = np.array([0.2126, 0.7152, 0.0722])

# Ниже этой доли альбедо не опускаем: у почти погашенного канала обратный
# множитель уходит в бесконечность, а по фото его всё равно не измерить —
# там уже шум матрицы, а не цвет стены.
MIN_ALBEDO = 0.02

DEFAULTS = {
    "enabled": False,
    "wall_color": "#ffffff",  # нейтраль: мод включён, но кадр не меняет
    "strength": 70,           # сила компенсации, % от полной
    "min_gain": 0.30,         # канал не ослабляем сильнее, чем в 1/min_gain раз
    "mode": "keep",           # keep — точный цвет, bright — вернуть светлоту
    "calibrate": False,       # светить белым, чтобы снять цвет стены
    "trim_r": 1.0,            # ручная доводка каналов поверх расчёта
    "trim_g": 1.0,
    "trim_b": 1.0,
    "max_boost": 2.0,         # предел общего усиления в режиме «Яркость»
}


def parse_color(value: str) -> np.ndarray:
    """«#rrggbb» (или «#rgb») -> доли 0..1. Мусор — белый, то есть нейтраль."""
    text = str(value).strip().lstrip("#")
    if len(text) == 3:
        text = "".join(c * 2 for c in text)
    try:
        channels = [int(text[i:i + 2], 16) for i in (0, 2, 4)]
    except (ValueError, IndexError):
        return np.ones(3)
    return np.array(channels, dtype=np.float64) / 255.0


def srgb_to_linear(value: np.ndarray) -> np.ndarray:
    """sRGB 0..1 -> линейная светимость: свет перемножается именно в ней."""
    return np.where(value <= 0.04045, value / 12.92, ((value + 0.055) / 1.055) ** 2.4)


def wall_albedo(color: str) -> np.ndarray:
    """Относительное альбедо стены по каналам, сильнейший канал = 1.

    Цвет снят при белом свете ленты, поэтому он уже и есть альбедо: остаётся
    линеаризовать и нормировать. Абсолютная светлота стены отбрасывается — её
    подсветкой не исправить (тёмная стена просто требует больше света), важны
    только пропорции каналов.
    """
    linear = srgb_to_linear(parse_color(color))
    top = float(linear.max())
    if top <= 0.0:
        return np.ones(3)  # чёрный цвет стены — считать нечего, не мешаем
    return np.clip(linear / top, MIN_ALBEDO, 1.0)


def channel_gains(settings: dict) -> np.ndarray:
    """Множители каналов кадра (в байтах) для заданных настроек.

    Полная компенсация — ``1 / альбедо``, приведённая к максимуму 1, чтобы
    остаться в пределах байта: слабый канал остаётся как есть, сильный
    приглушается. Дальше «сила» тянет множители обратно к единице (степенью, а
    не линейно — это множители), «предел» не даёт ослабить канал слишком
    сильно, и последней идёт ручная доводка.
    """
    merged = {**DEFAULTS, **settings}
    albedo = wall_albedo(merged["wall_color"])
    gains = float(albedo.min()) / albedo
    strength = min(max(float(merged["strength"]) / 100.0, 0.0), 1.0)
    gains = gains ** strength
    gains = np.maximum(gains, min(max(float(merged["min_gain"]), 0.0), 1.0))
    gains = gains * np.array(
        [float(merged["trim_r"]), float(merged["trim_g"]), float(merged["trim_b"])]
    )
    ceiling = max(float(merged["max_boost"]), 1.0)
    if str(merged["mode"]) == "bright":
        # вернуть кадру светлоту, потерянную на компенсации: ярче, но
        # насыщенные цвета упираются в 255 и пересвечиваются
        luma = float(LUMA @ gains)
        if luma > 0.0:
            gains = gains * min(1.0 / luma, ceiling)
        return np.clip(gains, 0.0, ceiling)
    return np.clip(gains, 0.0, 1.0)  # «Точный цвет»: только вниз


def build_lut(gains: np.ndarray) -> np.ndarray | None:
    """Таблица 256x3 «байт канала -> байт канала». None — множители нейтральны.

    Таблица считается при смене настроек, а не на каждом кадре: в горячем цикле
    остаётся одна выборка по индексу. Тот же приём, что в гамма-LUT ядра.
    """
    if np.allclose(gains, 1.0, atol=1.0 / 255.0):  # разница меньше младшего бита
        return None
    values = np.arange(256, dtype=np.float64)[:, None]
    return np.clip(np.rint(values * gains[None, :]), 0.0, 255.0).astype(np.uint8)


